'use strict';

const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { spawnSync } = require('node:child_process');
const { Client } = require('@modelcontextprotocol/sdk/client/index.js');
const { StdioClientTransport } = require('@modelcontextprotocol/sdk/client/stdio.js');

test('quick setup keeps a working runtime outside the download cache and preserves project config', { timeout: 120000 }, async t => {
    const temporary = fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), 'nasani-setup-')));
    t.after(() => fs.rmSync(temporary, { recursive: true, force: true }));
    const home = path.join(temporary, 'home');
    const project = path.join(temporary, 'project with spaces');
    const source = path.join(temporary, 'download-cache');
    fs.mkdirSync(home); fs.mkdirSync(project); fs.mkdirSync(source);
    const packageRoot = path.resolve(__dirname, '..');
    for (const name of ['bin', 'lib', 'skills', 'agents', 'package.json']) fs.cpSync(path.join(packageRoot, name), path.join(source, name), { recursive: true });
    const cli = path.join(source, 'bin/nasani.cjs');
    const env = { ...process.env, HOME: home, USERPROFILE: home };
    const run = (...args) => spawnSync(process.execPath, [cli, 'setup', '--project', project, ...args], { env, encoding: 'utf8', timeout: 90000 });
    assert.equal(run('--client', 'invalid').status, 1);
    assert.match(run().stderr, /--client codex\|claude\|both/);
    assert.deepEqual(fs.readdirSync(project), []);
    fs.mkdirSync(path.join(project, '.codex'));
    fs.writeFileSync(path.join(project, '.codex/config.toml'), 'model = "keep-existing-model"\n');
    fs.writeFileSync(path.join(project, '.mcp.json'), '{"mcpServers":{"other":{"command":"keep"}}}');
    const result = run('--client', 'both');
    assert.equal(result.status, 0, result.stdout + result.stderr);
    const codex = fs.readFileSync(path.join(project, '.codex/config.toml'), 'utf8');
    const claude = fs.readFileSync(path.join(project, '.mcp.json'), 'utf8');
    assert.match(codex, /^model = "keep-existing-model"/);
    const config = JSON.parse(claude);
    assert.equal(config.mcpServers.other.command, 'keep');
    const entry = config.mcpServers.nasani;
    const runtime = path.join(home, '.local/share/nasani-mcp/runtime/node_modules/@nasani/figma-mcp');
    assert.equal(entry.args[0], path.join(runtime, 'bin/nasani.cjs'));
    assert.equal(fs.lstatSync(runtime).isSymbolicLink(), false);
    assert.ok(!codex.includes(source));
    for (const name of ['.agents/skills/nasani-figma/SKILL.md', '.codex/agents/nasani-figma.toml', '.claude/skills/nasani-figma/SKILL.md', '.claude/agents/nasani-figma.md']) assert.ok(fs.existsSync(path.join(project, name)));
    assert.equal(run('--client', 'both').status, 0);
    assert.equal(fs.readFileSync(path.join(project, '.codex/config.toml'), 'utf8'), codex);
    assert.equal(fs.readFileSync(path.join(project, '.mcp.json'), 'utf8'), claude);
    const conflict = path.join(temporary, 'conflict'); fs.mkdirSync(conflict);
    fs.writeFileSync(path.join(conflict, '.mcp.json'), '{"mcpServers":{"nasani":{"command":"custom"}}}');
    const rejected = spawnSync(process.execPath, [entry.args[0], 'setup', '--client', 'both', '--project', conflict], { env, encoding: 'utf8' });
    assert.equal(rejected.status, 1);
    assert.match(rejected.stderr, /config differs/);
    assert.ok(!fs.existsSync(path.join(conflict, '.codex')));
    const skillHelper = path.join(project, '.agents/skills/nasani-figma/scripts/nasani.cjs');
    const skillProject = path.join(temporary, 'skill-only project'); fs.mkdirSync(skillProject);
    const call = (name, input = '{}', target = skillProject, selected = 'codex') => spawnSync(process.execPath, [skillHelper, '--project', target, '--client', selected, name], { env, input, encoding: 'utf8', timeout: 90000 });
    assert.equal(call('unknown').status, 1);
    assert.equal(call('nasani_environment', '[]').status, 1);
    assert.deepEqual(fs.readdirSync(skillProject), []);
    const firstUse = call('nasani_environment');
    assert.equal(firstUse.status, 0, firstUse.stderr);
    const environmentViaSkill = JSON.parse(JSON.parse(firstUse.stdout).content[0].text);
    assert.equal(environmentViaSkill.ok, true);
    assert.equal(environmentViaSkill.project_root, skillProject);
    assert.ok(fs.existsSync(path.join(skillProject, '.codex/config.toml')));
    assert.ok(!fs.existsSync(path.join(skillProject, '.mcp.json')));
    assert.ok(!fs.existsSync(path.join(skillProject, '.agents')));
    const skillConfig = fs.readFileSync(path.join(skillProject, '.codex/config.toml'), 'utf8');
    // A ready helper must work even if setup is unavailable; do not merely hide its logs.
    const setupPath = path.join(runtime, 'lib/setup.cjs');
    const setupSource = fs.readFileSync(setupPath, 'utf8');
    fs.writeFileSync(setupPath, 'throw new Error("Unexpected repeated setup");\n');
    const repeated = call('nasani_environment');
    assert.equal(repeated.status, 0, repeated.stderr);
    assert.equal(repeated.stderr, '');
    assert.equal(fs.readFileSync(path.join(skillProject, '.codex/config.toml'), 'utf8'), skillConfig);
    const output = path.join(skillProject, 'output'); fs.mkdirSync(output);
    fs.writeFileSync(path.join(output, 'index.html'), '<!doctype html><html lang="vi"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1.0"><title>Test</title><link rel="stylesheet" href="style.css"></head><body><div class="hero-wrap"><div class="wrap-content"><div class="hero-layout"><h2 class="hero__title">Test</h2></div></div></div></body></html>');
    fs.writeFileSync(path.join(output, 'style.css'), '.wrap-content{max-width:1200px;margin-inline:auto;padding-inline:15px;width:100%;box-sizing:border-box}.hero__title{color:#123456}');
    const formattedViaSkill = call('nasani_format', '{"directory":"output","content_width":1200}');
    assert.equal(formattedViaSkill.status, 0, formattedViaSkill.stdout + formattedViaSkill.stderr);
    assert.equal(formattedViaSkill.stderr, '');
    assert.ok(fs.readFileSync(path.join(output, 'index.html'), 'utf8').includes('\n'));
    assert.equal(call('nasani_validate', '{"directory":"output","content_width":1200}').status, 0);
    const escaped = call('nasani_assets', '{"directory":"../outside"}');
    assert.equal(escaped.status, 1);
    assert.equal(JSON.parse(escaped.stdout).isError, true);
    assert.equal(call('nasani_environment', '{}', conflict, 'claude').status, 1);
    assert.equal(fs.readFileSync(path.join(conflict, '.mcp.json'), 'utf8'), '{"mcpServers":{"nasani":{"command":"custom"}}}');
    const configPath = path.join(skillProject, '.codex/config.toml');
    fs.writeFileSync(configPath, '[mcp_servers.nasani]\ncommand = "custom"\n');
    const changedConfig = call('nasani_environment');
    assert.equal(changedConfig.status, 1);
    assert.match(changedConfig.stderr, /config differs/);
    assert.equal(fs.readFileSync(configPath, 'utf8'), '[mcp_servers.nasani]\ncommand = "custom"\n');
    fs.unlinkSync(configPath);
    const externalConfig = path.join(temporary, 'external-config'); fs.writeFileSync(externalConfig, skillConfig);
    fs.symlinkSync(externalConfig, configPath);
    assert.match(call('nasani_environment').stderr, /symlink/);
    assert.equal(fs.readFileSync(externalConfig, 'utf8'), skillConfig);
    fs.unlinkSync(configPath);
    fs.writeFileSync(setupPath, setupSource);
    const repaired = call('nasani_environment');
    assert.equal(repaired.status, 0, repaired.stderr);
    assert.equal(fs.readFileSync(configPath, 'utf8'), skillConfig);
    const claudeFirstUse = call('nasani_environment', '{}', skillProject, 'claude');
    assert.equal(claudeFirstUse.status, 0, claudeFirstUse.stderr);
    const claudeRepeated = call('nasani_environment', '{}', skillProject, 'claude');
    assert.equal(claudeRepeated.status, 0, claudeRepeated.stderr);
    assert.equal(claudeRepeated.stderr, '');
    fs.rmSync(source, { recursive: true });
    const transport = new StdioClientTransport({ command: entry.command, args: entry.args, env, stderr: 'pipe' });
    const client = new Client({ name: 'quick-setup-test', version: '1' });
    t.after(() => client.close());
    await client.connect(transport);
    const environment = await client.callTool({ name: 'nasani_environment', arguments: {} });
    const data = JSON.parse(environment.content[0].text);
    assert.equal(data.ok, true);
    assert.equal(data.mode, 'local');
    assert.equal(data.project_root, project);
});
