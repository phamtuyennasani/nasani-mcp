'use strict';

const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { spawnSync } = require('node:child_process');
const { Client } = require('@modelcontextprotocol/sdk/client/index.js');
const { StdioClientTransport } = require('@modelcontextprotocol/sdk/client/stdio.js');

test('quick setup keeps a working runtime outside the download cache and preserves project config', { timeout: 120000 }, async t => {
    const temporary = fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), 'nasani-setup-')));
    t.after(() => fs.rmSync(temporary, { recursive: true, force: true }));
    const home = path.join(temporary, 'home');
    const project = path.join(temporary, 'project with spaces');
    const source = path.join(temporary, 'download-cache');
    fs.mkdirSync(home); fs.mkdirSync(project); fs.mkdirSync(source);
    const packageRoot = path.resolve(__dirname, '..');
    for (const name of ['bin', 'lib', 'skills', 'agents', 'package.json']) fs.cpSync(path.join(packageRoot, name), path.join(source, name), { recursive: true });
    const cli = path.join(source, 'bin/nasani.cjs');
    const env = { ...process.env, HOME: home, USERPROFILE: home };
    const run = (...args) => spawnSync(process.execPath, [cli, 'setup', '--project', project, ...args], { env, encoding: 'utf8', timeout: 90000 });
    assert.equal(run('--client', 'invalid').status, 1);
    assert.match(run().stderr, /--client codex\|claude\|both/);
    assert.deepEqual(fs.readdirSync(project), []);
    fs.mkdirSync(path.join(project, '.codex'));
    fs.writeFileSync(path.join(project, '.codex/config.toml'), 'model = "keep-existing-model"\n');
    fs.writeFileSync(path.join(project, '.mcp.json'), '{"mcpServers":{"other":{"command":"keep"}}}');
    const result = run('--client', 'both');
    assert.equal(result.status, 0, result.stdout + result.stderr);
    const codex = fs.readFileSync(path.join(project, '.codex/config.toml'), 'utf8');
    const claude = fs.readFileSync(path.join(project, '.mcp.json'), 'utf8');
    assert.match(codex, /^model = "keep-existing-model"/);
    const config = JSON.parse(claude);
    assert.equal(config.mcpServers.other.command, 'keep');
    const entry = config.mcpServers.nasani;
    const runtime = path.join(home, '.local/share/nasani-mcp/runtime/node_modules/@nasani/figma-mcp');
    assert.equal(entry.args[0], path.join(runtime, 'bin/nasani.cjs'));
    assert.equal(fs.lstatSync(runtime).isSymbolicLink(), false);
    assert.ok(!codex.includes(source));
    for (const name of ['.agents/skills/nasani-figma/SKILL.md', '.codex/agents/nasani-figma.toml', '.claude/skills/nasani-figma/SKILL.md', '.claude/agents/nasani-figma.md']) assert.ok(fs.existsSync(path.join(project, name)));
    assert.equal(run('--client', 'both').status, 0);
    assert.equal(fs.readFileSync(path.join(project, '.codex/config.toml'), 'utf8'), codex);
    assert.equal(fs.readFileSync(path.join(project, '.mcp.json'), 'utf8'), claude);
    const conflict = path.join(temporary, 'conflict'); fs.mkdirSync(conflict);
    fs.writeFileSync(path.join(conflict, '.mcp.json'), '{"mcpServers":{"nasani":{"command":"custom"}}}');
    const rejected = spawnSync(process.execPath, [entry.args[0], 'setup', '--client', 'both', '--project', conflict], { env, encoding: 'utf8' });
    assert.equal(rejected.status, 1);
    assert.match(rejected.stderr, /config differs/);
    assert.ok(!fs.existsSync(path.join(conflict, '.codex')));
    fs.rmSync(source, { recursive: true });
    const transport = new StdioClientTransport({ command: entry.command, args: entry.args, env, stderr: 'pipe' });
    const client = new Client({ name: 'quick-setup-test', version: '1' });
    t.after(() => client.close());
    await client.connect(transport);
    const environment = await client.callTool({ name: 'nasani_environment', arguments: {} });
    const data = JSON.parse(environment.content[0].text);
    assert.equal(data.ok, true);
    assert.equal(data.mode, 'local');
    assert.equal(data.project_root, project);
});
